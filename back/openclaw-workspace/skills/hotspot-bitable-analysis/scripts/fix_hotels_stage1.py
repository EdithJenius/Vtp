body = json.dumps({"app_id": APP_ID, "app_secret": APP_SECRET}).encode()
req = urllib.request.Request('https://open.feishu.cn/open-apis/auth/v3/tenant_access_token/internal',
    data=body, headers={'Content-Type': 'application/json'})
with urllib.request.urlopen(req) as f:
    TOKEN = json.loads(f.read().decode())['tenant_access_token']
print(f"[Token] OK: {TOKEN[:20]}...")

MAIN_TOKEN = "ZdpRbPT2qaGsBvsqiNucQX1Knwh"

def api(method, url, data=None):
    headers = {'Authorization': f'Bearer {TOKEN}'}
    if data:
        payload = json.dumps(data).encode('utf-8')
        headers['Content-Type'] = 'application/json; charset=utf-8'
    else:
        payload = None
    r = urllib.request.Request(url, data=payload, method=method, headers=headers)
    with urllib.request.urlopen(r) as f:
        return json.loads(f.read().decode())

def get_table_id(name_contains):
    """Find table_id by name"""
    tables = api('GET',
        f'https://open.feishu.cn/open-apis/bitable/v1/apps/{MAIN_TOKEN}/tables?page_size=20')
    for t in tables.get('data', {}).get('items', []):
        if name_contains in t['name']:
            return t['table_id']
    return None

def add_hotels(table_id, hotel_records):
    """批量追加酒店记录"""
    for i in range(0, len(hotel_records), 10):
        batch = hotel_records[i:i+10]
        url = f'https://open.feishu.cn/open-apis/bitable/v1/apps/{MAIN_TOKEN}/tables/{table_id}/records/batch_create'
        payload = json.dumps({"records": [{"fields": r} for r in batch]}).encode('utf-8')
        req = urllib.request.Request(url, data=payload, method='POST',
            headers={'Authorization': f'Bearer {TOKEN}', 'Content-Type': 'application/json; charset=utf-8'})
        try:
            resp = urllib.request.urlopen(req)
            result = json.loads(resp.read())
            n = len(result.get('data', {}).get('records', []))
            print(f"  Batch {i//10+1}: {n} hotels added")
        except urllib.error.HTTPError as e:
            print(f"  Batch {i//10+1}: Error {e.code}: {e.read().decode()[:200]}")
        time.sleep(0.3)

