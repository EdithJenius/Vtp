def get_template(name):
    """获取单个模板的完整定义"""
    return TEMPLATES.get(name)


def list_templates():
    """列出所有模板（名称+简介）"""
    return [{"name": k, **v} for k, v in TEMPLATES.items()]


def get_recommended_templates(category):
    """根据品类推荐合适的模板列表"""
    return CATEGORY_TEMPLATE_MAP.get(category, ["干货/清单流", "真实UGC流"])


def get_templates_by_tag(tag):
    """按标签筛选模板"""
    return [{"name": k, **v} for k, v in TEMPLATES.items() if tag in v["tags"]]


def template_summary():
    """生成模板概览文本（供AI参考）"""
    lines = ["📋 10个风格模板库概览：\n"]
    for name, tmpl in TEMPLATES.items():
        lines.append(f"【{name}】{tmpl['description'][:40]}...")
        lines.append(f"  标签：{'/'.join(tmpl['tags'])}")
        lines.append(f"  标题：{tmpl['title_style'][:50]}")
        lines.append("")
    return "\n".join(lines)


