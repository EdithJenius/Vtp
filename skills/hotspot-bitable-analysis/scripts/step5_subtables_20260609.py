# 创建子表字段
def create_subtable(region_name, table_name, app_token, hotels):
    # 先创建子表
    fields_config = [
        {"field_name": "名称", "type": 1},
        {"field_name": "类别", "type": 3, "property": {"options": [{"name":"酒店住宿"},{"name":"景点景区"},{"name":"美食餐饮"},{"name":"文化活动"},{"name":"交通出行"},{"name":"旅行社·线路"}]}},
        {"field_name": "推荐理由", "type": 1},
        {"field_name": "参考价格", "type": 1},
        {"field_name": "关联热度", "type": 1},
        {"field_name": "详情链接", "type": 1},
        {"field_name": "备注", "type": 1},
    ]

    body = {"table": {"name": table_name, "fields": fields_config}}
    resp = api('POST', f'https://open.feishu.cn/open-apis/bitable/v1/apps/{app_token}/tables', body)
    tid = resp['data']['table_id']
    print(f"[子表] 创建: {table_name} -> {tid}")

    # 插入酒店数据 - 每批10条
    all_records = []
    for i, (name, reason, price) in enumerate(hotels, 1):
        all_records.append({
            "fields": {
                "名称": name,
                "类别": "酒店住宿",
                "推荐理由": reason,
                "参考价格": price,
                "关联热度": region_name,
                "详情链接": f"https://ditu.amap.com/search?query={urllib.parse.quote(name)}",
                "备注": f"#{i} {region_name}推荐酒店"
            }
        })

    # 按10条分批写入
    for batch_idx in range(0, len(all_records), 10):
        batch = all_records[batch_idx:batch_idx+10]
        resp = api('POST', f'https://open.feishu.cn/open-apis/bitable/v1/apps/{app_token}/tables/{tid}/records/batch_create',
            {"records": batch})
        if resp.get('code') == 0:
            print(f"  [写入] 批次{batch_idx//10+1}: {len(batch)}条")
        else:
            print(f"  [写入] 失败: {resp}")
        time.sleep(0.3)

    return tid

# 为每个地区创建子表
